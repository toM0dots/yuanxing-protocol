const assert = require('node:assert/strict');
const Campaign = require('../dist/exo-campaign.js');
global.ExoSandbox={enemy:(id,x,y,level)=>({id,x,y,level,hp:100})};
global.ExoWorld={elevation:()=>0};
const Fire=require('../dist/exo-fire-control.js');
const records=new Map([['exo-fire-control-v1','existing fire save'],['exo-expedition-v1','existing exploration save']]);
const storage={getItem:key=>records.get(key)||null,setItem:(key,value)=>records.set(key,value)};
const points={spawn:{x:100,y:100},route:[{x:100,y:120,radius:4},{x:140,y:140,radius:4},{x:100,y:160,radius:4}],refuge:{x:200,y:200,radius:5},range:{x:300,y:300,radius:10},lamps:[{x:110,y:170},{x:120,y:180},{x:130,y:190}]};
const make=()=>Campaign.create({storage,points,fireAPI:Fire});
let c=make();
assert.equal(c.objective().id,'crash');
assert.equal(c.checkpoint({x:100,y:100,angle:0}),false,'a campaign must be started before persisting a position');
assert.equal(c.award('stabilizer-installed'),false,'no generic award path can skip lessons');
assert.equal(c.award('crash-read'),true);
assert.equal(c.award('crash-read'),false,'reading twice must not advance twice');
assert.equal(c.state.started,true);
assert.equal(c.checkpoint({x:105,y:110,angle:9}),true);
assert.equal(c.checkpoint({x:Infinity,y:110,angle:0}),false);
assert.equal(c.checkpoint({x:22000,y:110,angle:0}),false);
assert.equal(c.checkpoint({x:105,y:110,angle:0,flight:true}),false);
for(const p of points.route)c.observe({unit:{...p,flight:true}});
assert.equal(c.state.routeIndex,0,'flying over the route does not replace ground inspection');
c.observe({unit:points.route[2]});
assert.equal(c.state.routeIndex,0,'route checkpoints are ordered');
c.observe({unit:points.route[0]});
assert.equal(c.state.routeIndex,1);
c=make();
assert.equal(c.state.routeIndex,1,'reload resumes the next route checkpoint');
assert.equal(c.state.checkpoint.x,105);
for(const p of points.route.slice(1))c.observe({unit:p});
assert.equal(c.objective().id,'lamps');
for(const p of points.lamps)c.observe({unit:p});
assert.equal(c.objective().id,'lamps','walking past a lamp is not a scan');
c.observe({unit:points.lamps[2],earned:new Set(Campaign.lampIds)});
assert.equal(c.objective().id,'mother');
assert.equal(c.award('captain-memory'),false);
assert.equal(c.award('mother-memory'),true);
assert.equal(c.award('captain-memory'),true);
assert.equal(c.objective().id,'refuge');
assert.equal(c.award('refuge-briefed'),false,'Old Lin is a physical destination');
c.observe({unit:points.refuge});
assert.equal(c.objective().action,'acknowledge');
c.observe({unit:points.range});
assert.equal(c.award('refuge-briefed'),false,'having visited earlier does not permit distant interaction');
c.observe({unit:points.refuge});
assert.equal(c.award('refuge-briefed'),true);
const fire=Fire.fresh();
fire.completed=true;
c.observe({unit:points.range,fireCourse:fire});
assert.equal(c.objective().id,'model','a legacy completion boolean cannot stand in for an installed model');
// Exercise the real model: varied training telemetry, gradient descent and
// install are the same operations used by the playable fire-control course.
const samples=[[100,-.8,-.4,-.3],[140,.7,.3,.2],[200,-.4,.5,-.1],[280,.6,-.7,.3],[350,-.9,.4,.5],[420,.3,-.2,-.2],[480,.8,.8,-.4],[540,-.6,-.3,.1],[620,.2,.6,.4],[710,-.2,-.6,-.5],[180,.9,-.8,.6],[390,-.7,.7,-.6]];
fire.logs=samples.map(([distance,wind,lead,height],i)=>({id:i+1,schema:3,distance,x:distance/500,wind,lead,height,y:Fire.drift(distance,i+1,{wind,lead,height}),role:'train',assisted:false,residual:10}));
assert.equal(Fire.train(fire,5000),true);
assert.equal(Fire.install(fire),true);
c.observe({unit:points.range,fireCourse:fire});
assert.equal(c.objective().id,'defense');
c.observe({unit:points.range,fireCourse:fire});
assert.equal(c.objective().id,'defense','victory needs genuinely held-out telemetry');
fire.logs.push({id:1,role:'test',assisted:true,distance:100,residual:.1});
assert.equal(c.telemetry(fire).test,0,'a fitted ID cannot count as held-out evidence');
fire.logs.pop();
for(const [i,distance] of [150,300,600].entries())fire.logs.push({id:100+i,role:'test',assisted:true,distance,residual:.2});
fire.completed=false;
c.observe({unit:points.range,fireCourse:fire});
assert.equal(c.objective().id,'defense','accurate test shots alone do not clear the defense');
fire.completed=true;
c.observe({unit:points.range,fireCourse:fire});
assert.equal(c.objective().id,'stabilizer');
assert.equal(c.award('stabilizer-installed'),false);
c.observe({unit:points.refuge,fireCourse:fire});
assert.equal(c.award('stabilizer-installed'),true);
assert.equal(c.bonuses().stabilizer,1.1);
assert.equal(c.award('stabilizer-installed'),false);
assert.equal(c.state.finished,true);
c=make();
assert.equal(c.bonuses().stabilizer,1.1,'upgrade effect survives reload');
assert.equal(records.get('exo-fire-control-v1'),'existing fire save');
assert.equal(records.get('exo-expedition-v1'),'existing exploration save');
assert.equal(Campaign.episodes.length,40);
assert.equal(Campaign.episodes.filter(e=>e.kind==='planned').length,31);
assert.match(c.panel(),/后 31 集为制作规划/);
assert.match(c.panel(),/最快的路线不带伤员/);
assert.match(c.panel(),/相位桥/);
const elements=Object.fromEntries(['campaign-hud-title','campaign-hud-episode','campaign-hud-detail'].map(id=>[id,{textContent:''}]));
const root={getElementById:id=>elements[id]};
c.updateHUD(root);assert.match(elements['campaign-hud-title'].textContent,/第一幕完成/);
elements['campaign-hud-title'].textContent='';c.updateHUD(root);
assert.match(elements['campaign-hud-title'].textContent,/第一幕完成/,'a remounted HUD is repopulated');
records.set(Campaign.KEY,JSON.stringify({version:1,done:['crash','stabilizer'],routeIndex:Infinity,checkpoint:{x:-1,y:2,angle:0}}));
c=make();assert.deepEqual(c.state.done,['crash'],'noncontiguous or malformed saved completion cannot skip the story');
assert.equal(c.state.checkpoint,null);
const failing=Campaign.create({points,storage:{getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}}});
assert.equal(failing.award('crash-read'),true);
assert.equal(failing.state.storageOK,false,'storage denial must not crash gameplay');
console.log('PASS: ordered grounded route, explicit lamp scans, narrative/refuge gates, real regression install, independent range evidence and defense, persistent physical upgrade/checkpoint, save isolation, honest 40-episode roadmap, remounted HUD, corrupt storage recovery');
