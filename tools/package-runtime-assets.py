"""Lossless transport copies; retain originals for older-browser fallback."""
from pathlib import Path
import gzip,hashlib,json,shutil,subprocess

root=Path(__file__).resolve().parents[1]/'dist'
models=['echo9-hero-v7/Echo9_Hero_V7.glb','canyon-v2/canyon-equipment-v87.glb','k09-hero-v1/k09-hangar-field.glb','hangar-v1/helios-kit.glb','wreck-v1/echo9-orbital-wreck.glb','interior-props-v1/interior-props.glb']
images=['canyon-v2/rock-diff-height.png','canyon-v2/trail-diff-height.png','hangar-v1/metal-normal-rough.png','hangar-v1/panel-normal-rough.png','ashland-v1/ash-normal-rough.png','vegetation-v88/foliage-atlas.png']
records={}
for name in models+images:
    path=root/'assets'/name
    original=path.read_bytes()
    if name in models:
        packed=path.with_suffix('.glb.gz');packed.write_bytes(gzip.compress(original,compresslevel=9,mtime=0))
    else:
        packed=path.with_suffix('.webp')
        subprocess.run([shutil.which('cwebp') or '/opt/local/bin/cwebp','-quiet','-lossless','-exact','-metadata','icc','-m','4',str(path),'-o',str(packed)],check=True)
    records[str(path.relative_to(root))]={'packed':str(packed.relative_to(root)),'bytes':packed.stat().st_size,'originalBytes':len(original),'sha256':hashlib.sha256(original).hexdigest()}
(root/'exo-asset-manifest.mjs').write_text('// Generated by tools/package-runtime-assets.py. Pixel/geometry data is unchanged.\nexport const packedAssets='+json.dumps(records,ensure_ascii=False,indent=2)+';\n')
print(json.dumps({'originalBytes':sum(r['originalBytes'] for r in records.values()),'packedBytes':sum(r['bytes'] for r in records.values()),'files':len(records)}))
